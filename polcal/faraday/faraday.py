"""Faraday rotation estimation and correction for quad-pol SAR.

Implements the Faraday rotation (FR) estimation and correction of

    F. J. Meyer and J. B. Nicoll, "Prediction, detection, and correction of
    Faraday rotation in full-polarimetric L-band SAR data," IEEE Trans.
    Geosci. Remote Sens., 46(10), 3076-3086, 2008.  Eqs. (13)-(15),

which use the circular-basis estimator of Bickel and Bates (1965) and the
system model of Freeman (2004).

Model. The ionosphere rotates the polarization plane by Omega on the way down
and again on the way back, so the one-way rotation matrix appears on both
sides of the scattering matrix (Meyer & Nicoll eq. 10; Freeman 2004):

    M = F(Omega) . S . F(Omega),   F(Omega) = [[ cos Omega, sin Omega],
                                              [-sin Omega, cos Omega]]

Unlike an orientation-angle rotation (F S F^T), this breaks reciprocity:
M_hv != M_vh even for a reciprocal target.

Estimator (Meyer & Nicoll eqs. 13-14). Transform to the circular basis,
Z = A M A with A = [[1, j], [j, 1]], then Omega = 1/4 arg(Z12 Z21^*).

Sign convention. Meyer & Nicoll write the matrices transposed,
[[M_hh, M_vh], [M_hv, M_vv]]. In the standard layout [[hh, hv], [vh, vv]]
used here this gives

    Z12 = (M_hv - M_vh) + j (M_hh + M_vv)
    Z21 = (M_vh - M_hv) + j (M_hh + M_vv)
    Omega = -1/4 * arg< Z12 . Z21^* >

which returns exactly the same number as the paper's eq. (14) for the same
data, so estimates are directly comparable with the paper. With this sign,
data generated by apply_faraday(..., Omega) is estimated as +Omega. (Taking
the paper's eq. (10) literally and feeding it to its eq. (14) returns -Omega;
the printed equations differ in the sign of Omega, a common inconsistency in
the FR literature. Magnitudes are unaffected.)

Correction (Meyer & Nicoll eq. 15): S = F(-Omega) . M . F(-Omega).

Practical notes from the paper:
* Average the complex product before taking the angle; they use a 10 x 10
  boxcar (the default window here).
* Receiver noise biases Omega towards zero at low SNR; they mask pixels with
  SNR below 10 dB before averaging (min_intensity_db below).
* Residual cross-talk creates an apparent rotation, so estimate on calibrated
  data. FR below 5 deg is generally considered acceptable.
* The estimate is unambiguous for |Omega| < 45 deg.
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from scipy.ndimage import uniform_filter

DEFAULT_WINDOW = 10  # boxcar size used by Meyer & Nicoll (2008), Sec. III-B


def rotation_matrix(omega: float) -> np.ndarray:
    c, s = np.cos(omega), np.sin(omega)
    return np.array([[c, s], [-s, c]])


def apply_faraday(hh, hv, vh, vv, omega):
    """Return F(omega) . M . F(omega) channel-wise (omega scalar or array, radians)."""
    c, s = np.cos(omega), np.sin(omega)
    # F M
    a11 = c * hh + s * vh
    a12 = c * hv + s * vv
    a21 = -s * hh + c * vh
    a22 = -s * hv + c * vv
    # (F M) F
    o_hh = a11 * c - a12 * s
    o_hv = a11 * s + a12 * c
    o_vh = a21 * c - a22 * s
    o_vv = a21 * s + a22 * c
    return o_hh, o_hv, o_vh, o_vv


def correct_faraday(hh, hv, vh, vv, omega):
    """Remove Faraday rotation, Meyer & Nicoll eq. (15): S = F(-omega) . M . F(-omega)."""
    return apply_faraday(hh, hv, vh, vv, -np.asarray(omega))


def _boxcar(z: np.ndarray, window: int) -> np.ndarray:
    if window <= 1:
        return z
    return uniform_filter(z.real, window) + 1j * uniform_filter(z.imag, window)


def bickel_bates_product(hh, hv, vh, vv) -> np.ndarray:
    """Per-pixel Z12 . Z21^* (complex128), Meyer & Nicoll eq. (13)."""
    hh, hv, vh, vv = (np.asarray(x, dtype=np.complex128) for x in (hh, hv, vh, vv))
    co = 1j * (hh + vv)
    z12 = (hv - vh) + co
    z21 = (vh - hv) + co
    return z12 * np.conj(z21)


def _omega(p) -> np.ndarray:
    """Meyer & Nicoll eq. (14) in the standard channel layout (see module docstring)."""
    return -0.25 * np.angle(p)


@dataclass
class FaradayEstimate:
    omega_scene_deg: float          # from the scene-averaged correlation (valid pixels)
    omega_map_deg: np.ndarray       # boxcar-averaged per-pixel estimate (NaN where masked)
    omega_range_deg: np.ndarray     # one estimate per range column (valid pixels)
    intensity_db: np.ndarray        # 10 log10 |<Z12 Z21*>|, the paper's brightness measure
    window: int
    min_intensity_db: float | None
    valid_fraction: float

    def summary(self) -> dict:
        m = self.omega_map_deg[np.isfinite(self.omega_map_deg)]
        return {
            "omega_scene_deg": float(self.omega_scene_deg),
            "omega_map_mean_deg": float(m.mean()),
            "omega_map_median_deg": float(np.median(m)),
            "omega_map_std_deg": float(m.std()),
            "omega_map_p05_deg": float(np.percentile(m, 5)),
            "omega_map_p95_deg": float(np.percentile(m, 95)),
            "omega_range_mean_deg": float(np.nanmean(self.omega_range_deg)),
            "omega_range_std_deg": float(np.nanstd(self.omega_range_deg)),
            "window": self.window,
            "min_intensity_db": self.min_intensity_db,
            "valid_fraction": self.valid_fraction,
        }


def estimate_faraday(hh, hv, vh, vv, window: int = DEFAULT_WINDOW,
                     min_intensity_db: float | None = None) -> FaradayEstimate:
    """Faraday rotation estimate in degrees (Meyer & Nicoll 2008, eqs. 13-14).

    window            boxcar size for the per-pixel map (paper: 10).
    min_intensity_db  optional low-SNR mask: pixels whose boxcar-averaged
                      circular cross-pol intensity 10 log10 |<Z12 Z21*>| is
                      below this value are excluded from all estimates. The
                      paper keeps only pixels with SNR >= 10 dB, i.e. set this
                      to (noise-equivalent level + 10 dB) in the data's units.
                      None (default) uses every pixel.
    """
    p = bickel_bates_product(hh, hv, vh, vv)
    p_avg = _boxcar(p, window)
    intensity_db = (10 * np.log10(np.abs(p_avg) + 1e-30)).astype(np.float32)

    if min_intensity_db is None:
        valid = np.ones(p.shape, dtype=bool)
    else:
        valid = intensity_db >= min_intensity_db
    if not valid.any():
        raise ValueError("min_intensity_db masks every pixel; lower the threshold.")

    p_valid = np.where(valid, p, 0)
    omega_scene = _omega(p_valid.sum())
    omega_map = np.where(valid, _omega(p_avg), np.nan)
    col_sum = p_valid.sum(axis=0)
    omega_range = np.where(valid.any(axis=0), _omega(col_sum), np.nan)

    return FaradayEstimate(
        omega_scene_deg=float(np.degrees(omega_scene)),
        omega_map_deg=np.degrees(omega_map).astype(np.float32),
        omega_range_deg=np.degrees(omega_range),
        intensity_db=intensity_db,
        window=window,
        min_intensity_db=min_intensity_db,
        valid_fraction=float(valid.mean()),
    )
